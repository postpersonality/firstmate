import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, symlinkSync, unlinkSync, linkSync, renameSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { Store } from '../src/store.ts';
import { firstmateHome } from './firstmate-home.ts';
import { router } from '../src/server.ts';

test('task diagnostics are bounded, metadata-bound, plain data and admit missing evidence', async t => {
  const root = mkdtempSync(join(tmpdir(), 'delo-diagnostics-'));
  const home = firstmateHome(root); mkdirSync(join(home, 'state'));
  const store = new Store({ firstmateHome: home });
  const worker = { id: 'broken', kind: 'scout', spawn_gen: 'generation-one', project: '/project', branch: 'fm/broken', paths: { worktree: { path: '/worktree' } }, current_state: { state: 'failed', detail: 'process exited' } };
  const meta = join(home, 'state/broken.meta'), log = join(home, 'state/broken.status');
  const source = 'kind=scout\nspawn_gen=generation-one\nproject=/project\nbranch=fm/broken\nworktree=/worktree\nendpoint_task_id=broken\n';
  writeFileSync(meta, source);
  writeFileSync(log, 'working: ancient\n' + 'failed [at=1]: старое\n'.repeat(2000) + 'failed [at=2]: <script>bad()</script> process exited\nblocked [at=3]: TOKEN=private-value\nfailed: API_KEY=private-api-value\nfailed: https://user:password@example.test/\n');
  t.mock.method(store.firstmate, 'snapshot', async () => ({ tasks: [worker] }));
  t.mock.method(store.firstmate, 'list', () => [{ id: 'broken', title: 'Ошибка', state: 'in_flight' as const, body: '' }]);
  t.mock.method(store.firstmate, 'show', () => ({ id: 'broken', title: 'Ошибка', state: 'in_flight' as const, body: '' }));
  t.mock.method(store.firstmate, 'receipts', () => ({}));
  t.mock.method(store.firstmate, 'terminal', async () => ({ available: false }));
  try {
    const handle = router(store);
    const card = await (await handle(new Request('http://localhost:4317/api/goals/broken'))).json();
    assert.ok(card.worker.diagnostics, 'card includes task-owned diagnostics');
    const diagnostics = card.worker.diagnostics;
    assert.ok(diagnostics.entries.length <= 12);
    assert.equal(diagnostics.truncated, true);
    assert.match(JSON.stringify(diagnostics), /process exited/);
    assert.doesNotMatch(JSON.stringify(diagnostics), /private-value|private-api-value|user:password|ancient/);
    assert.match(diagnostics.note, /истори/);
    assert.equal((await handle(new Request('http://localhost:4317/api/goals/broken?path=/etc/passwd'))).status, 200);
    assert.doesNotMatch(JSON.stringify(await (await handle(new Request('http://localhost:4317/api/goals/broken?path=/etc/passwd'))).json()), /root:x:/);
    writeFileSync(meta, source.replace('generation-one', 'another-generation'));
    assert.deepEqual((await store.worker('broken') as any).diagnostics.entries, []);
    writeFileSync(meta, source);
    unlinkSync(log); writeFileSync(join(root, 'secret'), 'failed: hidden-file'); symlinkSync(join(root, 'secret'), log);
    const unavailable = (await store.worker('broken') as any).diagnostics;
    assert.deepEqual(unavailable.entries, []); assert.match(unavailable.note, /не подтвержд/);
    unlinkSync(log); linkSync(join(root, 'secret'), log);
    assert.deepEqual((await store.worker('broken') as any).diagnostics.entries, [], 'hard-linked files cannot expose unrelated content');
    unlinkSync(log); writeFileSync(log, 'failed: real task failure');
    unlinkSync(meta); writeFileSync(join(root, 'other-meta'), source); symlinkSync(join(root, 'other-meta'), meta);
    assert.deepEqual((await store.worker('broken') as any).diagnostics.entries, [], 'metadata symlinks are refused');
    unlinkSync(meta); writeFileSync(meta, source + 'kind=ship\n');
    assert.deepEqual((await store.worker('broken') as any).diagnostics.entries, [], 'ambiguous metadata is refused');
    writeFileSync(meta, source); worker.id = 'another-task';
    assert.deepEqual((await store.worker('broken') as any).diagnostics.entries, [], 'another task cannot provide diagnostics');
    worker.id = 'broken';
    renameSync(join(home, 'state'), join(home, 'hidden-state')); symlinkSync(join(home, 'hidden-state'), join(home, 'state'));
    assert.deepEqual((await store.worker('broken') as any).diagnostics.entries, [], 'the state directory cannot redirect outside its fixed location');
    assert.equal((await handle(new Request('http://localhost:4317/api/goals/%2e%2e%2fsecret'))).status, 400);
    store.firstmate.snapshot = async () => { throw new Error('snapshot unavailable'); };
    const withoutSnapshot = await handle(new Request('http://localhost:4317/api/goals/broken'));
    assert.equal(withoutSnapshot.status, 200, 'missing runtime evidence does not hide the task assignment');
    const unknown = await withoutSnapshot.json();
    assert.equal(unknown.worker.current, 'Состояние неизвестно');
    assert.equal(unknown.worker.diagnostics.available, false);
  } finally { rmSync(root, { recursive: true, force: true }); }
});
